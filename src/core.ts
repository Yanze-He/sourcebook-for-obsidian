export const ACTIVE_START = '<!-- sourcebook:active:start -->';
export const ACTIVE_END = '<!-- sourcebook:active:end -->';
export const REMOVED_START = '<!-- sourcebook:removed:start -->';
export const REMOVED_END = '<!-- sourcebook:removed:end -->';
export const ENTRY_END = '<!-- sourcebook:entry:end -->';

export type DocumentLanguage = 'zh' | 'en';
export type Kind = 'image' | 'text' | 'note' | 'link' | 'file' | 'audio' | 'video' | 'post' | 'conversation';
export type EntryType = 'file' | 'text' | 'link';

/** Picker-specific presentation data. Content may be stored in Markdown while
 * retaining its original material modality (for example, a picked web page). */
export interface PickerMetadata {
    modality: Kind;
    title?: string;
    /** Original selected text, retained for Picker compatibility and recovery. */
    contentText?: string;
    sourceUrl?: string;
    sourceTitle?: string;
    sourceOrigin?: string;
    thumbnailUrl?: string;
    faviconUrl?: string;
    /** Duration supplied by Picker for captured audio or video, in seconds. */
    durationSeconds?: number;
    pickedAt?: string;
}

export interface Entry {
    id: string;
    type: EntryType;
    removed: boolean;
    note: string;
    /** Language used when this entry block was created. Old entries inherit the Book language. */
    language?: DocumentLanguage;
    /** Native Markdown link generated by Obsidian, for file entries only. */
    target?: string;
    /** Display title. Editing a file title renames that Vault file. */
    title?: string;
    /** Inline text body for text entries only. */
    body?: string;
    /** Public-style source or link URL. */
    url?: string;
    /** Persisted modification time for inline text and link entries. */
    updatedAt?: string;
    /** Provenance and display information supplied by Picker. */
    picker?: PickerMetadata;
}

