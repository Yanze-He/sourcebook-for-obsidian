export function fail(message: string): never { throw new Error(message); }
export function id(): string { return crypto.randomUUID(); }
export function entryId(): string { return `sb-entry-${id().replace(/-/g, '').slice(-16)}`; }
export function message(error: unknown): string { return error instanceof Error ? error.message : String(error); }

export function plainTitle(value: string): string {
    const cleaned = value.replace(/[\r\n\t]/g, ' ').trim();
    if (!cleaned) fail('A title is required / 请填写标题');
    if (cleaned.length > 160) fail('Title is too long / 标题不能超过 160 字符');
    return cleaned;
}

export function safeName(value: string): string {
    const forbidden = '<>:"/\\|?*[]#^';
    let s = [...value.normalize('NFC')].map(char => char.codePointAt(0)! <= 31 || forbidden.includes(char) ? '-' : char).join('').replace(/[. ]+$/g, '').replace(/^[. ]+/g, '').slice(0, 100);
    if (/^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(s)) s = `_${s}`;
    return s || 'untitled';
}

export function safeRelative(path: string): string {
    if (!path || path.startsWith('/') || path.includes('\\') || [...path].some(char => char.codePointAt(0)! <= 31) || /^[A-Za-z]:/.test(path)) fail('Unsafe Vault path');
    if (path.split('/').some(p => !p || p === '.' || p === '..' || p.startsWith('.'))) fail('Unsafe Vault path');
    return path;
}

export function webUrl(value: string): string {
    const u = new URL(value.trim());
    if (!['https:', 'http:'].includes(u.protocol) || u.username || u.password) fail('Only public-style HTTP(S) links without credentials are accepted');
    return u.href;
}

export function kindFor(name: string): Kind {
    const ext = name.toLowerCase().split('.').pop() || '';
    if (ext === 'md') return 'note';
    if (['png', 'jpg', 'jpeg', 'webp', 'gif', 'avif', 'bmp', 'svg'].includes(ext)) return 'image';
    if (['mp3', 'm4a', 'wav', 'ogg', 'flac'].includes(ext)) return 'audio';
    if (['mp4', 'mov', 'webm', 'mkv'].includes(ext)) return 'video';
    return 'file';
}

export function canPreviewImage(path: string): boolean { return /\.(png|jpe?g|webp|gif|avif|bmp)$/i.test(path); }
export function titleFromPath(path: string): string {
    const file = path.split('/').pop() || path;
    return file.replace(/\.md$/i, '').replace(/\.[^.]+$/, '');
}

export function serialize(meta: Frontmatter, body: string): string {
    const fields = Object.entries(meta).map(([key, value]) => {
        if (!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(key)) fail('Invalid metadata key');
        return `${key}: ${JSON.stringify(value)}`;
    });
    return `---\n${fields.join('\n')}\n---\n\n${body.trim()}\n`;
}

export function stringField(meta: Frontmatter, key: string): string { return typeof meta[key] === 'string' ? meta[key] as string : ''; }

function quoteLines(value: string): string[] {
    if (!value) return ['>'];
    return value.replace(/\r\n/g, '\n').split('\n').map(line => line ? `> ${line}` : '>');
}

function section(label: string, entryIdValue: string, key: string, value: string): string[] {
    return [
        `> **${label}**`,
        `> <!-- sourcebook:field ${entryIdValue}:${key}:start -->`,
        ...quoteLines(value),
        `> <!-- sourcebook:field ${entryIdValue}:${key}:end -->`
    ];
}

export function renderEntry(entry: Entry, language: DocumentLanguage): string {
    const entryLanguage = entry.language || language;
    const labels = entryLanguage === 'zh'
        ? { material: '素材', text: '文本', source: '来源', link: '链接', note: '本册备注', untitled: '未命名' }
        : { material: 'Material', text: 'Text', source: 'Source', link: 'Link', note: 'Context in this Book', untitled: 'Untitled' };
    const descriptor = {
        id: entry.id,
        type: entry.type,
        ...(entry.title ? { title: entry.title } : {}),
        ...(entry.language ? { language: entry.language } : {}),
        ...(entry.updatedAt ? { updatedAt: entry.updatedAt } : {}),
        ...(entry.picker ? { picker: entry.picker } : {})
    };
    const marker = `<!-- sourcebook:entry ${JSON.stringify(descriptor)} -->`;
    const lines = [marker, `> [!sourcebook]${entry.title ? ` ${plainTitle(entry.title)}` : ''}`];
    if (entry.type === 'file') lines.push(...section(labels.material, entry.id, 'material', entry.target || ''));
    if (entry.type === 'text') {
        lines.push(...section(labels.text, entry.id, 'text', entry.body || ''));
        if (entry.url) lines.push('>', ...section(labels.source, entry.id, 'source', `<${entry.url}>`));
    }
    if (entry.type === 'link') lines.push(...section(labels.link, entry.id, 'link', `<${entry.url || ''}>`));
    lines.push('>', ...section(labels.note, entry.id, 'note', entry.note || ''));
    lines.push(`^${entry.id}`, ENTRY_END);
    return lines.join('\n');
}

function unquote(line: string): string | undefined {
    if (line === '>') return '';
    if (line.startsWith('> ')) return line.slice(2);
    return undefined;
}

function fieldValue(body: string, entryIdValue: string, key: string): string {
    const lines = body.split('\n').map(unquote).filter((value): value is string => value !== undefined);
    const start = `<!-- sourcebook:field ${entryIdValue}:${key}:start -->`;
    const end = `<!-- sourcebook:field ${entryIdValue}:${key}:end -->`;
    const startIndex = lines.indexOf(start), endIndex = lines.indexOf(end);
    if (startIndex < 0 || endIndex < 0 || endIndex < startIndex) return '';
    return lines.slice(startIndex + 1, endIndex).join('\n').trim();
}

function cleanUrl(value: string): string {
    const trimmed = value.trim().replace(/^<|>$/g, '');
    return trimmed ? webUrl(trimmed) : '';
}

function pickerMetadata(value: unknown): PickerMetadata | undefined {
    if (!value || typeof value !== 'object' || Array.isArray(value)) return undefined;
    const raw = value as Record<string, unknown>;
    const modality = raw.modality;
    if (!['image', 'text', 'note', 'link', 'file', 'audio', 'video', 'post', 'conversation'].includes(String(modality))) return undefined;
    const text = (key: string, limit = 300): string | undefined => typeof raw[key] === 'string' ? raw[key].trim().slice(0, limit) || undefined : undefined;
    const url = (key: string): string | undefined => {
        const value = text(key, 2048);
        if (!value) return undefined;
        try { return webUrl(value); } catch { return undefined; }
    };
    const duration = typeof raw.durationSeconds === 'number' && Number.isFinite(raw.durationSeconds) && raw.durationSeconds > 0
        ? raw.durationSeconds
        : undefined;
    return {
        modality: modality as Kind,
        ...(text('title', 160) ? { title: text('title', 160) } : {}),
        ...(text('contentText', 20_000) ? { contentText: text('contentText', 20_000) } : {}),
        ...(url('sourceUrl') ? { sourceUrl: url('sourceUrl') } : {}),
        ...(text('sourceTitle', 300) ? { sourceTitle: text('sourceTitle', 300) } : {}),
        ...(text('sourceOrigin', 300) ? { sourceOrigin: text('sourceOrigin', 300) } : {}),
        ...(url('thumbnailUrl') ? { thumbnailUrl: url('thumbnailUrl') } : {}),
        ...(url('faviconUrl') ? { faviconUrl: url('faviconUrl') } : {}),
        ...(duration ? { durationSeconds: duration } : {}),
        ...(text('pickedAt', 80) ? { pickedAt: text('pickedAt', 80) } : {})
    };
}

export function parseEntry(block: string, removed: boolean): Entry {
    const firstLineEnd = block.indexOf('\n');
    const markerLine = firstLineEnd >= 0 ? block.slice(0, firstLineEnd) : block;
    const marker = markerLine.match(/^<!-- sourcebook:entry (\{.*\}) -->$/);
    if (!marker) fail('Invalid Sourcebook entry marker');
    let descriptor: unknown;
    try { descriptor = JSON.parse(marker[1] || ''); } catch { fail('Invalid Sourcebook entry descriptor'); }
    if (!descriptor || typeof descriptor !== 'object') fail('Invalid Sourcebook entry descriptor');
    const raw = descriptor as Record<string, unknown>;
    const entryType = raw.type;
    const eid = raw.id;
    const language: DocumentLanguage | undefined = raw.language === 'zh' || raw.language === 'en' ? raw.language : undefined;
    const localized = language ? { language } : {};
    const updatedAt = typeof raw.updatedAt === 'string' && Number.isFinite(Date.parse(raw.updatedAt)) ? raw.updatedAt : undefined;
    const timestamped = updatedAt ? { updatedAt } : {};
    const picker = pickerMetadata(raw.picker);
    const pickerField = picker ? { picker } : {};
    const descriptorTitle = typeof raw.title === 'string' && raw.title.trim() ? plainTitle(raw.title) : undefined;
    const titleField = descriptorTitle ? { title: descriptorTitle } : {};
    if (typeof eid !== 'string' || !/^sb-entry-[a-zA-Z0-9_-]+$/.test(eid) || !['file', 'text', 'link'].includes(String(entryType))) fail('Invalid Sourcebook entry identity');
    const body = block.slice(firstLineEnd + 1, block.lastIndexOf(ENTRY_END)).trim();
    if (!new RegExp(`^\\^${eid.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'm').test(body)) fail(`Missing block ID for ${eid}`);
    const callout = body.match(/^> \[!sourcebook\](?: (.*))?$/m);
    const note = fieldValue(body, eid, 'note');
    if (entryType === 'file') {
        const target = fieldValue(body, eid, 'material');
        if (!/^!?\[\[[^\]]+\]\]$/.test(target.trim())) fail(`Invalid material link in ${eid}`);
        return { id: eid, type: 'file', removed, note, target: target.trim(), ...titleField, ...localized, ...timestamped, ...pickerField };
    }
    const title = plainTitle(callout?.[1] || 'Untitled');
    if (entryType === 'text') return { id: eid, type: 'text', removed, note, title, body: fieldValue(body, eid, 'text'), url: cleanUrl(fieldValue(body, eid, 'source')), ...localized, ...timestamped, ...pickerField };
    return { id: eid, type: 'link', removed, note, title, url: cleanUrl(fieldValue(body, eid, 'link')), ...localized, ...timestamped, ...pickerField };
}

function entriesFromRegion(value: string, removed: boolean): Entry[] {
    const entries: Entry[] = [];
    let cursor = 0;
    while (cursor < value.length) {
        const start = value.indexOf('<!-- sourcebook:entry ', cursor);
        if (start < 0) break;
        const end = value.indexOf(ENTRY_END, start);
        if (end < 0) fail('Unclosed Sourcebook entry');
        const block = value.slice(start, end + ENTRY_END.length);
        entries.push(parseEntry(block, removed));
        cursor = end + ENTRY_END.length;
    }
    const stripped = value.replace(/<!-- sourcebook:entry [\s\S]*?<!-- sourcebook:entry:end -->/g, '').trim();
    if (stripped) fail('Unsupported text inside a managed Sourcebook entry region');
    return entries;
}

function region(body: string, startMarker: string, endMarker: string): string {
    const start = body.indexOf(startMarker), end = body.indexOf(endMarker);
    if (start < 0 || end < 0 || end < start) fail('Book managed regions are missing or malformed');
    return body.slice(start + startMarker.length, end).trim();
}

export function decodeBook(path: string, parsed: Parsed): Book {
    const meta = parsed.meta;
    if (meta.sb_schema !== SCHEMA || meta.sb_type !== 'book') fail('Unsupported Book schema');
    const bookId = stringField(meta, 'sb_id');
    if (!bookId) fail('Missing Book ID');
    const entries = [...entriesFromRegion(region(parsed.body, ACTIVE_START, ACTIVE_END), false), ...entriesFromRegion(region(parsed.body, REMOVED_START, REMOVED_END), true)];
    const ids = new Set<string>();
    for (const entry of entries) {
        if (ids.has(entry.id)) fail(`Duplicate Book entry ID: ${entry.id}`);
        ids.add(entry.id);
    }
    const language: DocumentLanguage = stringField(meta, 'sb_language') === 'zh' ? 'zh' : 'en';
    return { id: bookId, path, title: plainTitle(titleFromPath(path)), entries, archived: meta.archived === true, language };
}

function replaceRegion(body: string, startMarker: string, endMarker: string, entries: Entry[], language: DocumentLanguage): string {
    const start = body.indexOf(startMarker), end = body.indexOf(endMarker);
    if (start < 0 || end < 0 || end < start) fail('Book managed regions are missing or malformed');
    const content = entries.map(entry => renderEntry(entry, language)).join('\n\n');
    return `${body.slice(0, start + startMarker.length)}\n${content ? `\n${content}\n` : ''}${body.slice(end)}`;
}

export function rewriteBookBody(body: string, entries: Entry[], language: DocumentLanguage): string {
    let next = replaceRegion(body, ACTIVE_START, ACTIVE_END, entries.filter(e => !e.removed), language);
    next = replaceRegion(next, REMOVED_START, REMOVED_END, entries.filter(e => e.removed), language);
    return next;
}

export function newBookBody(language: DocumentLanguage): string {
    if (language === 'zh') return `## 项目说明\n\n在这里填写这本素材册的项目背景。\n\n## 素材\n\n${ACTIVE_START}\n${ACTIVE_END}\n\n## 已移出\n\n${REMOVED_START}\n${REMOVED_END}`;
    return `## Project context\n\nAdd the project context for this Book here.\n\n## Materials\n\n${ACTIVE_START}\n${ACTIVE_END}\n\n## Removed\n\n${REMOVED_START}\n${REMOVED_END}`;
}

export function emptyRegistry(): Registry { return { schemaVersion: 2, materials: {} }; }
export function parseRegistry(value: string): Registry {
    let parsed: unknown;
    try { parsed = JSON.parse(value); } catch { fail('Sourcebook metadata registry is invalid JSON'); }
    if (!parsed || typeof parsed !== 'object') fail('Invalid Sourcebook metadata registry');
    const raw = parsed as Record<string, unknown>;
    if (raw.schemaVersion !== 2 || !raw.materials || typeof raw.materials !== 'object' || Array.isArray(raw.materials)) fail('Unsupported Sourcebook metadata registry');
    const materials: Record<string, MaterialMetadata> = {};
    for (const [key, value] of Object.entries(raw.materials as Record<string, unknown>)) {
        if (!value || typeof value !== 'object') fail('Invalid material metadata');
        const item = value as Record<string, unknown>;
        if (typeof item.id !== 'string' || item.id !== key || typeof item.path !== 'string') fail('Invalid material metadata identity');
        safeRelative(item.path);
        const sourceUrl = typeof item.sourceUrl === 'string' && item.sourceUrl ? webUrl(item.sourceUrl) : undefined;
        materials[key] = { id: key, path: item.path, sourceUrl, sourceTitle: typeof item.sourceTitle === 'string' ? item.sourceTitle : undefined, capturedAt: typeof item.capturedAt === 'string' ? item.capturedAt : undefined, captureMethod: ['picker', 'import', 'manual'].includes(String(item.captureMethod)) ? item.captureMethod as MaterialMetadata['captureMethod'] : undefined, sha256: typeof item.sha256 === 'string' ? item.sha256 : undefined };
    }
    return { schemaVersion: 2, materials };
}

export class SerialQueue {
    private tail: Promise<unknown> = Promise.resolve();
    run<T>(fn: () => Promise<T>): Promise<T> {
        const result = this.tail.then(fn);
        this.tail = result.catch(() => undefined);
        return result;
    }
}

export function searchText(item: Resolved, query: string, kind: string): boolean {
    if (kind && item.kind !== kind) return false;
    return [item.title, item.body, item.url, item.entry.note, item.filePath].join('\n').toLocaleLowerCase().includes(query.trim().toLocaleLowerCase());
}

